        assertThat(responseAtBoundary.isAvailable()).isTrue();
        assertThat(responseAtBoundary.getRequestedQuantity()).isEqualTo(requestedQuantityAtBoundary);
        assertThat(responseAtBoundary.getAvailableQuantity()).isEqualTo(availableQuantity);
